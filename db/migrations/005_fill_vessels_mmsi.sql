DO $$
DECLARE n_missing integer;
BEGIN
    SELECT count(*) INTO n_missing FROM public.vessels v LEFT JOIN flag_mid f USING (flag_country) WHERE f.mid IS NULL;
    IF n_missing > 0 THEN RAISE EXCEPTION '% vessels have a flag_country without MID', n_missing; END IF;
END $$;

UPDATE public.vessels v
   SET mmsi = f.mid || lpad(((v.vessel_id * 7919 + 42) % 1000000)::text, 6, '0')
  FROM flag_mid f
 WHERE f.flag_country = v.flag_country;

DO $$
DECLARE n_null integer; n_dup integer; n_bad_mid integer;
BEGIN
    SELECT count(*) INTO n_null FROM public.vessels WHERE mmsi IS NULL;
    SELECT count(*) - count(DISTINCT mmsi) INTO n_dup FROM public.vessels;
    SELECT count(*) INTO n_bad_mid FROM public.vessels v JOIN flag_mid f USING (flag_country) WHERE left(v.mmsi, 3) <> f.mid;
    IF n_null + n_dup + n_bad_mid > 0 THEN
        RAISE EXCEPTION 'mmsi check failed: null=%, duplicates=%, wrong MID=%', n_null, n_dup, n_bad_mid;
    END IF;
END $$;

ALTER TABLE public.vessels ALTER COLUMN mmsi SET NOT NULL;

COMMIT;
